static void spi2_write_byte(uint8_t b) {
  while ((SPI2->sts & (1UL << 1)) == 0UL) { /* TDBE */
  }
  SPI2->dt = b;
}

static void spi2_wait_idle(void) {
  while ((SPI2->sts & (1UL << 7)) != 0UL) { /* BF */
  }
}

static void lcd_write_cmd(uint8_t cmd) {
  gpio_clear(LCD_CS_PORT, LCD_CS_PIN);
  gpio_clear(LCD_DC_PORT, LCD_DC_PIN);
  spi2_write_byte(cmd);
  spi2_wait_idle();
  gpio_set(LCD_CS_PORT, LCD_CS_PIN);
}

static void lcd_write_data(const uint8_t *buf, uint32_t len) {
  gpio_clear(LCD_CS_PORT, LCD_CS_PIN);
  gpio_set(LCD_DC_PORT, LCD_DC_PIN);
  for (uint32_t i = 0U; i < len; i++) {
    spi2_write_byte(buf[i]);
  }
  spi2_wait_idle();
  gpio_set(LCD_CS_PORT, LCD_CS_PIN);
}

static void lcd_write_data_byte(uint8_t v) {
  lcd_write_data(&v, 1U);
}

static void lcd_set_window(uint16_t x0, uint16_t y0, uint16_t x1, uint16_t y1) {
  uint8_t buf[4];

  lcd_write_cmd(0x2AU);
  buf[0] = (uint8_t)(x0 >> 8);
  buf[1] = (uint8_t)(x0 & 0xFFU);
  buf[2] = (uint8_t)(x1 >> 8);
  buf[3] = (uint8_t)(x1 & 0xFFU);
  lcd_write_data(buf, 4U);

  lcd_write_cmd(0x2BU);
  buf[0] = (uint8_t)(y0 >> 8);
  buf[1] = (uint8_t)(y0 & 0xFFU);
  buf[2] = (uint8_t)(y1 >> 8);
  buf[3] = (uint8_t)(y1 & 0xFFU);
  lcd_write_data(buf, 4U);

  lcd_write_cmd(0x2CU);
}

void lcd_init(void) {
  static const uint8_t b2_seq[] = {0x0CU, 0x0CU, 0x00U, 0x33U, 0x33U};
  static const uint8_t d0_seq[] = {0xA4U, 0xA1U};
  static const uint8_t e0_seq[] = {
    0xD0U, 0x04U, 0x0DU, 0x11U, 0x13U, 0x2BU, 0x3FU,
    0x54U, 0x4CU, 0x18U, 0x0DU, 0x0BU, 0x1FU, 0x23U
  };
  static const uint8_t e1_seq[] = {
    0xD0U, 0x04U, 0x0CU, 0x11U, 0x13U, 0x2CU, 0x3FU,
    0x44U, 0x51U, 0x2FU, 0x1FU, 0x1FU, 0x20U, 0x23U
  };

  CRM->apb2en |= CRM_APB2_GPIOA | CRM_APB2_GPIOB | CRM_APB2_GPIOC;
  CRM->apb1en |= CRM_APB1_SPI2;

  /* Control pins */
  gpio_set(LCD_CS_PORT, LCD_CS_PIN);
  gpio_set(LCD_DC_PORT, LCD_DC_PIN);
  gpio_set(LCD_RST_PORT, LCD_RST_PIN);
  gpio_clear(LCD_BL_PORT, LCD_BL_PIN);

  gpio_config_pin(LCD_CS_PORT, LCD_CS_PIN, GPIO_CFG_OUT_PP_50);
  gpio_config_pin(LCD_DC_PORT, LCD_DC_PIN, GPIO_CFG_OUT_PP_50);
  gpio_config_pin(LCD_RST_PORT, LCD_RST_PIN, GPIO_CFG_OUT_PP_50);
  gpio_config_pin(LCD_BL_PORT, LCD_BL_PIN, GPIO_CFG_OUT_PP_50);

  /* SPI2 SCK (PB13) & MOSI (PB15) */
  gpio_config_pin(LCD_SCK_PORT, LCD_SCK_PIN, GPIO_CFG_MUX_PP_50);
  gpio_config_pin(LCD_MOSI_PORT, LCD_MOSI_PIN, GPIO_CFG_MUX_PP_50);

  /* SPI2 Master, 8-bit, SW CS, Mode 0, PCLK1/4 = 2 MHz */
  SPI2->ctrl2 = 0UL;
  SPI2->ctrl1 = (1UL << 9) | (1UL << 8) | (1UL << 6) | (1UL << 3) | (1UL << 2);

  /* Hardware Reset sequence matching V1.9 timings */
  gpio_set(LCD_RST_PORT, LCD_RST_PIN);
  delay_ms(10U);
  gpio_clear(LCD_RST_PORT, LCD_RST_PIN);
  delay_ms(20U);
  gpio_set(LCD_RST_PORT, LCD_RST_PIN);
  delay_ms(120U);

  /* ST7789V init sequence extracted from V1.9 */
  lcd_write_cmd(0x11U); /* SLPOUT */
  delay_ms(120U);

  lcd_write_cmd(0x36U); /* MADCTL */
  lcd_write_data_byte(LCD_MADCTL_DEFAULT);

  lcd_write_cmd(0x3AU); /* COLMOD: 16-bit RGB565 */
  lcd_write_data_byte(0x05U);

  lcd_write_cmd(0xB2U);
  lcd_write_data(b2_seq, sizeof(b2_seq));

  lcd_write_cmd(0xB7U);
  lcd_write_data_byte(0x35U);

  lcd_write_cmd(0xBBU);
  lcd_write_data_byte(0x28U);

  lcd_write_cmd(0xC0U);
  lcd_write_data_byte(0x2CU);

  lcd_write_cmd(0xC2U);
  lcd_write_data_byte(0x01U);

  lcd_write_cmd(0xC3U);
  lcd_write_data_byte(0x0BU);

  lcd_write_cmd(0xC4U);
  lcd_write_data_byte(0x20U);

  lcd_write_cmd(0xC6U);
  lcd_write_data_byte(0x0FU);

  lcd_write_cmd(0xD0U);
  lcd_write_data(d0_seq, sizeof(d0_seq));

  lcd_write_cmd(0xE0U);
  lcd_write_data(e0_seq, sizeof(e0_seq));

  lcd_write_cmd(0xE1U);
  lcd_write_data(e1_seq, sizeof(e1_seq));

  lcd_write_cmd(0x21U); /* INVON (IPS panel) */
  lcd_write_cmd(0x29U); /* DISPON */
  delay_ms(20U);

  /* Turn backlight ON */
  gpio_set(LCD_BL_PORT, LCD_BL_PIN);
}

void lcd_fill_rect(uint16_t x, uint16_t y, uint16_t w, uint16_t h, uint16_t color) {
  if (x >= LCD_WIDTH || y >= LCD_HEIGHT || w == 0U || h == 0U) {
    return;
  }
  if ((uint32_t)x + w > LCD_WIDTH) {
    w = (uint16_t)(LCD_WIDTH - x);
  }
  if ((uint32_t)y + h > LCD_HEIGHT) {
    h = (uint16_t)(LCD_HEIGHT - y);
  }

  lcd_set_window(x, y, (uint16_t)(x + w - 1U), (uint16_t)(y + h - 1U));

  uint8_t hi = (uint8_t)(color >> 8);
  uint8_t lo = (uint8_t)(color & 0xFFU);
  uint32_t total = (uint32_t)w * (uint32_t)h;

  gpio_clear(LCD_CS_PORT, LCD_CS_PIN);
  gpio_set(LCD_DC_PORT, LCD_DC_PIN);
  for (uint32_t i = 0U; i < total; i++) {
    spi2_write_byte(hi);
    spi2_write_byte(lo);
  }
  spi2_wait_idle();
  gpio_set(LCD_CS_PORT, LCD_CS_PIN);
}

void lcd_draw_char(uint16_t x, uint16_t y, char ch, uint16_t fg, uint16_t bg, uint8_t scale) {
  if (scale == 0U) {
    scale = 1U;
  }
  uint8_t c = (uint8_t)ch;
  if (c < 0x20U || c > 0x7EU) {
    c = (uint8_t)' ';
  }
  const uint8_t *glyph = k_font5x7[c - 0x20U];
  uint16_t cw = (uint16_t)(6U * scale);
  uint16_t ch_h = (uint16_t)(7U * scale);

  if (x + cw > LCD_WIDTH || y + ch_h > LCD_HEIGHT) {
    return;
  }

  lcd_set_window(x, y, (uint16_t)(x + cw - 1U), (uint16_t)(y + ch_h - 1U));

  uint8_t fg_hi = (uint8_t)(fg >> 8), fg_lo = (uint8_t)(fg & 0xFFU);
  uint8_t bg_hi = (uint8_t)(bg >> 8), bg_lo = (uint8_t)(bg & 0xFFU);

  gpio_clear(LCD_CS_PORT, LCD_CS_PIN);
  gpio_set(LCD_DC_PORT, LCD_DC_PIN);

  for (uint8_t row = 0U; row < 7U; row++) {
    for (uint8_t sy = 0U; sy < scale; sy++) {
      for (uint8_t col = 0U; col < 6U; col++) {
        uint8_t on = (col < 5U) ? (uint8_t)((glyph[col] >> row) & 1U) : 0U;
        uint8_t hi = on ? fg_hi : bg_hi;
        uint8_t lo = on ? fg_lo : bg_lo;
        for (uint8_t sx = 0U; sx < scale; sx++) {
          spi2_write_byte(hi);
          spi2_write_byte(lo);
        }
      }
    }
  }

  spi2_wait_idle();
  gpio_set(LCD_CS_PORT, LCD_CS_PIN);
}

void lcd_draw_string(uint16_t x, uint16_t y, const char *s, uint16_t fg, uint16_t bg, uint8_t scale) {
  if (scale == 0U) {
    scale = 1U;
  }
  uint16_t step = (uint16_t)(6U * scale);
  while (*s != '\0') {
    if (x + step > LCD_WIDTH) {
      break;
    }
    lcd_draw_char(x, y, *s++, fg, bg, scale);
    x = (uint16_t)(x + step);
  }
}
